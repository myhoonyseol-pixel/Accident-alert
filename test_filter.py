def evaluate(cfg, label):
    tp = fp = fn = 0
    to_ai = 0
    problems = []
    for expect, title in SAMPLES:
        fired = filters.match(cfg, title) is not None
        if expect == "TRUE":
            if fired:
                tp += 1
            else:
                fn += 1
                problems.append(("놓침", title))
        elif expect == "AI":
            if fired:
                to_ai += 1            # 설계대로 AI에게 넘어감
            # 키워드 단계에서 이미 걸렸다면 그것도 정상입니다.
            # (AI 호출을 아끼는 것이므로 문제가 아님)
        else:
            if fired:
                fp += 1
                problems.append(("오탐", title))

    n_true = sum(1 for e, _ in SAMPLES if e == "TRUE")
    n_false = sum(1 for e, _ in SAMPLES if e == "FALSE")
    n_ai = sum(1 for e, _ in SAMPLES if e == "AI")

    print(f"\n{'=' * 68}\n{label}\n{'=' * 68}")
    print("  [1차 그물 — 키워드]")
    print(f"    받아야 할 사고 {n_true}건 중 감지  : {tp}건  (놓침 {fn}건)")
    print(f"    걸러야 할 노이즈 {n_false}건 중 오탐: {fp}건")
    print()
    print("  [2차 판정 — AI]")
    print(f"    의미 판단 케이스 {n_ai}건 중 {to_ai}건이 AI로 넘어감")
    print(f"    나머지 {n_ai - to_ai}건은 키워드 단계에서 이미 걸러짐 (AI 호출 절약)")
    print("    ※ 이런 기사를 키워드로 막으려 하면 진짜 사고까지 버립니다")
    if problems:
        print("\n  문제 사례:")
        for kind, t in problems:
            print(f"    [{kind}] {t}")
    else:
        print("\n  문제 사례 없음")
    return fp


def check_dedup(cfg):
    print(f"\n{'=' * 68}\n같은 사고 중복 제거 (매체 3곳이 같은 사고를 보도)\n{'=' * 68}")
    kept, token_sets = [], []
    for title in DUP_GROUP:
        toks = filters.tokenize(title)
        if any(filters.similarity(toks, prev) >= cfg.DUP_SIMILARITY for prev in token_sets):
            print(f"  [중복차단] {title}")
            continue
        token_sets.append(toks)
        kept.append(title)
        print(f"  [발송   ] {title}")
    print(f"  → 기사 {len(DUP_GROUP)}건 → 알림 {len(kept)}건")
    return len(kept)


def check_real_case(cfg):
    print(f"\n{'=' * 68}\n실제 사고 검증 — 2026-08-25 울산 아파트 신축현장 붕괴 (매체 4곳)\n{'=' * 68}")
    detected, prev, sent = 0, [], 0
    for title in REAL_DUP_GROUP:
        if not filters.match(cfg, title):
            print(f"  [놓침    ] {title}")
            continue
        detected += 1
        toks = filters.tokenize(title)
        if filters.is_duplicate(cfg, toks, prev):
            print(f"  [중복차단] {title}")
        else:
            prev.append(toks)
            sent += 1
            print(f"  [발송    ] {title}")
    print(f"  → 기사 {len(REAL_DUP_GROUP)}건 중 {detected}건 감지, 카톡 {sent}건")
    return detected, sent


